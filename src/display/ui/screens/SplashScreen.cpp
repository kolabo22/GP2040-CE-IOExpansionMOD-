void SplashScreen::init() {
    getRenderer()->clearScreen();
    splashStartTime = getMillis();
    configMode = DriverManager::getInstance().isConfigMode();
}

void SplashScreen::shutdown() {
    clearElements();
}

void SplashScreen::drawScreen() {
    uint32_t elapsed = getMillis() - splashStartTime;

    // --- 1. 起動から1.0秒間は「溜め」（何も表示しない） ---
    // JQ8900が機種判定を待っている時間と同期させます
    if (elapsed < 1000) {
        getRenderer()->clearScreen();
        return;
    }

    // --- 2. 1.0秒経過後：音が鳴るタイミングで機種別ロゴを表示 ---
    InputMode mode = DriverManager::getInstance().getInputMode();
    const uint8_t* selectedLogo = nullptr;

    // InputMode（機種）に応じて表示するロゴを切り替え
    // PDFの定義に基づいた正確な分岐
    switch (mode) {
        case INPUT_MODE_XINPUT:       selectedLogo = L_XINPUT; break;         // 0001
        case INPUT_MODE_SWITCH:       selectedLogo = L_SWITCH; break;         // 0002
        case INPUT_MODE_PS3:          selectedLogo = L_PS3; break;            // 0003
        case INPUT_MODE_PS4:          selectedLogo = L_PS4; break;            // 0004
        case INPUT_MODE_XBONE:        selectedLogo = L_XBOXONE; break;        // 0006
        case INPUT_MODE_KEYBOARD:     selectedLogo = L_KEYBOARD; break;       // 0007
        case INPUT_MODE_NEOGEO:       selectedLogo = L_NEOGEO; break;         // 0008
        case INPUT_MODE_PCEMINI:      selectedLogo = L_PCENGINE; break;       // 0010
        case INPUT_MODE_MDMINI:       selectedLogo = L_MEGADRIVE; break;      // 0011
        case INPUT_MODE_XBOXORIGINAL: selectedLogo = L_XBOX_OG; break;       // 0012
        case INPUT_MODE_SWITCH_PRO:   selectedLogo = L_SWITCH_PRO; break;     // 0013
        case INPUT_MODE_PSCLASSIC:    selectedLogo = L_PS_CLASSIC; break;      // 0016
        case INPUT_MODE_ASTRO:        selectedLogo = L_ASTRO_CITY; break;     // 0017
        case INPUT_MODE_EGRET:        selectedLogo = L_EGRET2; break;         // 0018
        case INPUT_MODE_PS5:          selectedLogo = L_PS5; break;            // 0020
        case INPUT_MODE_P5GENERAL:    selectedLogo = L_P5GENERAL; break;
				case INPUT_MODE_GENERIC:    	selectedLogo = L_GENERIC; break;
			
        default:
            // 該当がない場合はWebConfigで設定されたデフォルト画像を表示
            selectedLogo = (uint8_t*) getDisplayOptions().splashImage.bytes;
            break;
    }

    if (selectedLogo != nullptr) {
        // 全画面(128x64)でロゴを描画
        // 引数: データ, 幅, 高さ, 1ラインあたりのバイト数(128/8=16), X, Y, カラー
        getRenderer()->drawSprite((uint8_t*)selectedLogo, 128, 64, 16, -2, 0, 1);
    }
}

int8_t SplashScreen::update() {
    uint32_t elapsedDuration = getMillis() - splashStartTime;
    
    // ロゴを最低でも1.5秒間は見せるため、トータルの表示時間を2.5秒以上に強制する
    uint32_t splashDuration = getDisplayOptions().splashDuration;
    if (splashDuration < 2500) splashDuration = 2500; 

    if (!configMode) {
        // 通常起動時：設定時間が来たら対戦画面（BUTTONS）へ
        if (elapsedDuration >= splashDuration) {
            return DisplayMode::BUTTONS;
        }
    } else {
        // WebConfig（S2）起動時：B2ボタンで設定指示画面へ
        uint16_t buttonState = getGamepad()->state.buttons;
        if (prevButtonState && !buttonState) {
            if (prevButtonState == GAMEPAD_MASK_B2) {
                prevButtonState = 0;
                return DisplayMode::CONFIG_INSTRUCTION;
            }
        }
        prevButtonState = buttonState;
    }
    return -1; // 状態維持
}
